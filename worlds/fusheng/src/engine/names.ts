const SURNAMES: Record<string, string[]> = {
  // 为什么只有部分国家有姓氏：多数文化里全名即可，中日韩越单独取姓更显真实
  CHN: ['陈', '王', '李', '张', '刘', '杨', '赵', '周'],
  VNM: ['阮', '陈', '黎', '范'],
};

/** 取一个（国家，性别）的姓名。rng 必须是引擎主 rng——名字进黄金快照 */
export function makeName(rng: () => number, country: string, gender: 'm' | 'f'): string {
  const table = TABLES[country] ?? GENERIC;
  const pool = gender === 'm' ? table.m : table.f;
  const given = pool[Math.floor(rng() * pool.length)];
  const surnames = SURNAMES[country];
  if (surnames) {
    const surname = surnames[Math.floor(rng() * surnames.length)];
    return gender === 'm' || country !== 'VNM' ? surname + given : surname + '氏' + given; // 越南女名「阮氏梅」式
  }
  return given;
}

/** 亲友名：配偶/子女——复用出生国名池但不复用本人 rng 调用序列（各自独立抽取） */
export function makeRelativeName(rng: () => number, country: string, gender: 'm' | 'f'): string {
  return makeName(rng, country, gender);
}
